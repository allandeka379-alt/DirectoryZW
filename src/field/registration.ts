import crypto from "node:crypto";
import { z } from "zod";
import type { Db } from "../db/client.js";
import { one } from "../db/client.js";
import { createBusiness } from "../directory/businesses.js";
import { haversineKm, type Gazetteer } from "../directory/gazetteer.js";
import type { Taxonomy } from "../directory/taxonomy.js";
import type { FileStore } from "../storage.js";
import { normalizeText, normalizeZimPhone } from "../text.js";
import type { Agent } from "./agents.js";

const MAX_PHOTO_BYTES = 2 * 1024 * 1024;
const PHOTO_TYPES: Record<string, string> = { "image/jpeg": "jpg", "image/png": "png", "image/webp": "webp" };

export const FieldRegistrationSchema = z.object({
  /** Generated by the app for each registration, so a retried upload never creates a second listing. */
  clientRef: z.string().min(8).max(64).regex(/^[a-zA-Z0-9_-]+$/),
  name: z.string().trim().min(2).max(80),
  phone: z.string().min(9).max(20),
  categories: z.array(z.string()).min(1).max(3),
  description: z.string().trim().max(300).optional(),
  keywords: z.string().trim().max(200).optional(),
  areaId: z.number().int().positive().optional(),
  lat: z.number().min(-90).max(90).optional(),
  lng: z.number().min(-180).max(180).optional(),
  gpsAccuracyM: z.number().nonnegative().max(100_000).optional(),
  checks: z.object({ premisesSeen: z.boolean(), idChecked: z.boolean() }),
  /** The owner agreed, in person, to be listed and to receive customer messages. */
  consent: z.literal(true),
  /** Save even though another listing uses this phone number (e.g. two shops, one owner). */
  allowDuplicatePhone: z.boolean().optional(),
  // Photos of the business only. Copies of IDs or registration papers are never accepted.
  photos: z
    .array(
      z.object({
        kind: z.enum(["shopfront", "inside", "price_list"]),
        contentType: z.string(),
        dataBase64: z.string().max(Math.ceil((MAX_PHOTO_BYTES * 4) / 3) + 4),
      }),
    )
    .max(3)
    .default([]),
});
export type FieldRegistration = z.infer<typeof FieldRegistrationSchema>;

export interface DuplicateMatch {
  id: string;
  name: string;
  phone: string;
  area: string | null;
  verification: string;
  reason: "same_phone" | "similar_name_nearby";
}

export type RegistrationResult =
  | { status: "created" | "exists"; id: string; verification: "verified" | "registered" }
  | { status: "duplicate"; matches: DuplicateMatch[] }
  | { status: "invalid"; error: string };

export interface FieldDeps {
  db: Db;
  taxonomy: Taxonomy;
  gazetteer: Gazetteer;
  store: FileStore;
}

/** A business registered in person by a field agent. Verified only if both checks were done. */
export async function registerFromField(deps: FieldDeps, agent: Agent, input: FieldRegistration): Promise<RegistrationResult> {
  const { db, taxonomy, gazetteer, store } = deps;
  const existing = await one<{ id: string; verification: "verified" | "registered" }>(
    db,
    "SELECT id, verification FROM businesses WHERE client_ref = $1",
    [input.clientRef],
  );
  if (existing) return { status: "exists", ...existing };

  const phone = normalizeZimPhone(input.phone);
  if (!phone) return { status: "invalid", error: "The phone number doesn't look right." };
  const badCategories = input.categories.filter((s) => {
    const c = taxonomy.get(s);
    return !c || c.risk === "blocked" || c.risk === "restricted";
  });
  if (badCategories.length) return { status: "invalid", error: `These categories can't be listed: ${badCategories.join(", ")}` };
  const area = input.areaId != null ? gazetteer.get(input.areaId) : input.lat != null && input.lng != null ? gazetteer.nearest(input.lat, input.lng) : undefined;
  if (!area) return { status: "invalid", error: "Pick the area, or capture the GPS location." };
  const photos = [];
  for (const p of input.photos) {
    const ext = PHOTO_TYPES[p.contentType];
    if (!ext) return { status: "invalid", error: `Photos must be JPEG, PNG or WebP, not ${p.contentType}.` };
    const data = Buffer.from(p.dataBase64, "base64");
    if (!data.length || data.length > MAX_PHOTO_BYTES) return { status: "invalid", error: "Each photo must be under 2 MB." };
    photos.push({ kind: p.kind, contentType: p.contentType, ext, data });
  }

  if (!input.allowDuplicatePhone) {
    const matches = await findDuplicates(db, gazetteer, { phone, name: input.name, lat: input.lat ?? area.lat, lng: input.lng ?? area.lng });
    if (matches.length) return { status: "duplicate", matches };
  }

  const verified = input.checks.premisesSeen && input.checks.idChecked;
  const id = await createBusiness(db, {
    name: input.name,
    description: input.description,
    keywords: input.keywords,
    phone,
    areaId: area.id,
    lat: input.lat ?? area.lat,
    lng: input.lng ?? area.lng,
    categories: input.categories,
    source: "field",
    verified,
    verifiedBy: agent.name,
    optedIn: true,
    registeredBy: agent.id,
    clientRef: input.clientRef,
    gpsAccuracyM: input.gpsAccuracyM ?? null,
    checks: input.checks,
  });
  for (const p of photos) {
    const photoId = crypto.randomUUID();
    const key = `photos/${id}/${photoId}.${p.ext}`;
    await store.put(key, p.data, p.contentType);
    await db.query(
      "INSERT INTO business_photos (id, business_id, kind, storage_key, content_type, bytes) VALUES ($1, $2, $3, $4, $5, $6)",
      [photoId, id, p.kind, key, p.contentType, p.data.length],
    );
  }
  return { status: "created", id, verification: verified ? "verified" : "registered" };
}

const NAME_NOISE = new Set(["the", "and", "of", "shop", "store", "stores", "enterprises", "enterprise", "pvt", "ltd", "private", "limited", "co", "company", "services", "zim", "zimbabwe"]);

function nameTokens(name: string): Set<string> {
  return new Set(normalizeText(name).split(" ").filter((w) => w.length > 1 && !NAME_NOISE.has(w)));
}

/** Listings that are probably this business already: same number, or a similar name within 1 km. */
export async function findDuplicates(
  db: Db,
  gazetteer: Gazetteer,
  q: { phone?: string | null; name?: string; lat?: number; lng?: number },
): Promise<DuplicateMatch[]> {
  const out = new Map<string, DuplicateMatch>();
  const rows = await db.query<{ id: string; name: string; phone: string; area_id: number | null; verification: string; lat: number | null; lng: number | null }>(
    `SELECT id, name, phone, area_id, verification, lat, lng FROM businesses
      WHERE status <> 'removed'
        AND (phone = $1 OR ($2::float8 IS NOT NULL
             AND lat BETWEEN $2::float8 - 0.02 AND $2::float8 + 0.02
             AND lng BETWEEN $3::float8 - 0.02 AND $3::float8 + 0.02))
      LIMIT 200`,
    [q.phone ?? "", q.lat ?? null, q.lng ?? null],
  );
  const wanted = q.name ? nameTokens(q.name) : new Set<string>();
  for (const r of rows) {
    const area = gazetteer.get(r.area_id)?.name ?? null;
    if (q.phone && r.phone === q.phone) {
      out.set(r.id, { id: r.id, name: r.name, phone: r.phone, area, verification: r.verification, reason: "same_phone" });
      continue;
    }
    if (!wanted.size || q.lat == null || q.lng == null || r.lat == null || r.lng == null) continue;
    if (haversineKm(q.lat, q.lng, r.lat, r.lng) > 1) continue;
    const theirs = nameTokens(r.name);
    const shared = [...wanted].filter((w) => theirs.has(w)).length;
    const similarity = shared / Math.max(1, Math.min(wanted.size, theirs.size));
    if (shared > 0 && similarity >= 0.5) {
      out.set(r.id, { id: r.id, name: r.name, phone: r.phone, area, verification: r.verification, reason: "similar_name_nearby" });
    }
  }
  return [...out.values()].slice(0, 5);
}
